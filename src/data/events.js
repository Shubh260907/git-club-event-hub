function createEvent({
  id,
  title,
  category,
  date,
  endTime = "04:00 PM",
  venue = "Seminar Hall, CSPIT",
  shortDescription,
  longDescription,
  tags,
  seatsTotal = 80,
  seatsLeft = 80,
  registrationDeadline,
  featured = false,
  organizers: eventOrganizers = organizers,
  agenda = [
    { time: "10:00 AM", title: "Welcome and introductions" },
    { time: "11:00 AM", title: "Main session and hands-on activity" },
    { time: "03:30 PM", title: "Showcase, questions, and closing" },
  ],
  prerequisites = ["Bring a laptop and your CHARUSAT ID."],
  faqs = [
    { q: "Who can attend?", a: "All CHARUSAT students are welcome." },
    { q: "What should I bring?", a: "Bring your laptop and student ID." },
  ],
  participants,
  recap,
}) {
  return {
    id,
    title,
    category,
    date,
    startTime: "10:00 AM",
    endTime,
    venue,
    shortDescription,
    longDescription,
    tags,
    seatsTotal,
    seatsLeft,
    registrationDeadline,
    featured,
    organizers: eventOrganizers,
    agenda,
    prerequisites,
    faqs,
    ...(participants === undefined ? {} : { participants }),
    ...(recap === undefined ? {} : { recap }),
  }
}

